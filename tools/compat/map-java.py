"""Emit Java data only after generated profile JSON exists."""
import json
from pathlib import Path
import sys
R=Path(sys.argv[sys.argv.index('--evidence-root')+1]).resolve() if '--evidence-root' in sys.argv else Path(__file__).resolve().parent
labels=['cn73932','cn74132','cn74332','cn74532','gp73932']
profiles=[json.loads((R/('map-'+l+'.json')).read_text(encoding='utf-8')) for l in labels]
q=lambda s:json.dumps(str(s),ensure_ascii=True)
lines=['package io.github.mianxyz.fanqiecustomizer;','import java.util.Map;','import java.util.HashMap;','/** Generated by .verify/569/map-java.py; static DEX definition evidence, not runtime behavior. */','final class HostSymbolData {',' private HostSymbolData() {}',' static synchronized void registerAll() {','  if (registered) return;']
for i,p in enumerate(profiles):
 lines.append('  profile'+str(i)+'();')
 lines.append('  HostSymbols.registerValidation('+q(p['package'])+','+str(p['version_code'])+'L,v'+str(i)+'());')
lines+=['  registered=true;',' }',' private static boolean registered;']
for i,p in enumerate(profiles):
 lines+=[' private static void profile'+str(i)+'() {','  Map<String,String> c=new HashMap<>(),m=new HashMap<>(),f=new HashMap<>(),r=new HashMap<>();']
 for tab,v in [('classes','c'),('methods','m'),('fields','f'),('resources','r')]:
  rows=list(p[tab].items())
  for offset in range(0,len(rows),100):lines.append('  p'+str(i)+tab+str(offset)+'('+v+');')
 lines+=['  HostSymbols.register('+q(p['package'])+','+str(p['version_code'])+'L,c,m,f,r);',' }']
 for tab in ['classes','methods','fields','resources']:
  rows=list(p[tab].items())
  for offset in range(0,len(rows),100):
   lines+=[' private static void p'+str(i)+tab+str(offset)+'(Map<String,String> out) {']
   lines+=['  out.put('+q(k)+','+q(v)+');' for k,v in rows[offset:offset+100]];lines+=[' }']
lines+=[' /** C: canonical,actual,super,interfaces; M/F: canonicalOwner,name,canonicalDescriptor,actualOwner,name,descriptor,static. */',' static String[][] validation(String pkg,long code) {']
for i,p in enumerate(profiles):lines.append('  if ('+q(p['package'])+'.equals(pkg) && code=='+str(p['version_code'])+'L) return v'+str(i)+'();')
lines+=['  return new String[0][];',' }']
for i,p in enumerate(profiles):
 rows=[]
 for v in p['validation']:
  if v['kind']=='class':row=['C',v['canonical'],v['actual'],(v['superclass'][1:-1].replace('/','.') if v['superclass'] else ''),','.join(x[1:-1].replace('/','.') for x in v['interfaces'])]
  else:row=['M' if v['kind']=='method' else 'F',v['canonical_owner'],v['canonical_name'],v['canonical_descriptor'],v['owner'],v['name'],v['descriptor'],str(v['static']).lower()]
  rows.append('new String[]{'+','.join(q(x) for x in row)+'}')
 lines+=[' private static String[][] v'+str(i)+'() {','  String[][] out=new String['+str(len(rows))+'][];']
 for off in range(0,len(rows),80):lines.append('  v'+str(i)+'part'+str(off)+'(out);')
 lines+=['  return out;',' }']
 for off in range(0,len(rows),80):
  lines+=[' private static void v'+str(i)+'part'+str(off)+'(String[][] out) {']
  lines+=['  out['+str(n)+']='+rows[n]+';' for n in range(off,min(off+80,len(rows)))];lines+=[' }']
lines+=['}']
(R/'map-HostSymbolData.java').write_text(chr(10).join(lines)+chr(10),encoding='utf-8')
print('Java generated',len(lines),'lines')
